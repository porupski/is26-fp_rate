def generate_sub_csvs(df, results_dir):
    """Write one CSV per model type in MODEL_TYPES_TO_PLOT."""
    for mtype in MODEL_TYPES_TO_PLOT:
        sub = df[df["Model_Type"] == mtype]
        if sub.empty:
            print(f"  [SKIP] No rows for {mtype}")
            continue
        out_path = os.path.join(results_dir, f"collected_results_{mtype}.csv")
        sub.to_csv(out_path, index=False)
        print(f"  {len(sub):>5} rows -> {os.path.basename(out_path)}")


