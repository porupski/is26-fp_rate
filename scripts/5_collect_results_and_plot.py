# Interleaved order: for each predictor group, base then between then within.
# Slots that don't exist in data are simply skipped.
_MASTER_PREDICTOR_ORDER = [
    "Speaker gender",
    "Speaker age",
    "Speech rate",
    "Speech rate (between)",
    "Speech rate (within)",
    "Sentiment",
    "Sentiment (between)",
    "Sentiment (within)",
    "Political orientation",
    "Power status",
]


def _build_master_predictor_order(df_mtype):
    """
    Build the full y-axis predictor list for a master plot:
      1. Interleaved main predictors (base + Mundlak variants)
      2. All interaction terms (sorted)

    Returns (predictor_order, divider_y) where divider_y is the
    y-coordinate for the horizontal separator line, or None.
    """
    present = set(df_mtype["Predictor_Clean"].unique())
    present.discard("Intercept")
    for lbl in LANG_LABELS:
        present.discard(lbl)

    # Main predictors in interleaved order
    main = [p for p in _MASTER_PREDICTOR_ORDER if p in present]

    # Interaction terms
    known_main = set(_MASTER_PREDICTOR_ORDER) | set(LANG_LABELS) | {"Intercept"}
    interactions = sorted(p for p in present if p not in known_main and "×" in p)
    extras       = sorted(p for p in present if p not in known_main and "×" not in p)

    # Divider position: between last main predictor and first interaction
    divider_y = None
    if main and interactions:
        divider_y = len(main) + len(extras) - 0.5   # sits between groups

    order = main + extras + interactions
    return order, divider_y


def _collect_master_rows(df_mtype, parl):
    """
    For a given model type and parliament, collect exactly the right
    rows for the master plot:

      - BASE track  → all main-effect predictors (non-interaction):
                       gender, age, speech rate, sentiment, orientation, status
      - MUNDLAK track → ONLY the decomposed variants:
                         speech rate (between/within), sentiment (between/within)
      - INT_* tracks → only the interaction term (the × predictor),
                        not the main effects that come along for free

    This gives exactly 1 dot per label — no overlaps.

    Returns a DataFrame subset with Predictor_Clean already set.
    """
    sub = df_mtype[df_mtype["Parliament"] == parl].copy()
    if sub.empty:
        return sub
    sub["Predictor_Clean"] = sub["Predictor"].apply(clean_predictor_name)

    # Drop intercept and lang dummies
    drop_labels = {"Intercept"} | set(LANG_LABELS)
    sub = sub[~sub["Predictor_Clean"].isin(drop_labels)]

    # Identify track types — must work for both FP Count (BASE, MUNDLAK,
    # INT_*) and FP Duration (GAMMA, GAMMA_MUNDLAK, GAMMA_INT_*).
    tracks = sub["Track"].unique()
    base_tracks    = [t for t in tracks
                      if t.upper() in ("BASE", "GAMMA")
                      or t.upper().endswith("_BASE")]
    mundlak_tracks = [t for t in tracks if "MUNDLAK" in t.upper()]
    int_tracks     = [t for t in tracks
                      if t.upper().startswith("INT_")
                      or "_INT_" in t.upper()]

    # Labels that only come from the Mundlak track (decomposed variants)
    _MUNDLAK_ONLY = {
        "Speech rate (between)", "Speech rate (within)",
        "Sentiment (between)",   "Sentiment (within)",
    }

    parts = []

    # BASE: all non-interaction predictors, excluding the decomposed variants
    if base_tracks:
        base_rows = sub[sub["Track"].isin(base_tracks)]
        base_rows = base_rows[~base_rows["Predictor_Clean"].str.contains("×", na=False)]
        base_rows = base_rows[~base_rows["Predictor_Clean"].isin(_MUNDLAK_ONLY)]
        parts.append(base_rows)

    # MUNDLAK: only the between/within decomposed predictors
    if mundlak_tracks:
        mundlak_rows = sub[sub["Track"].isin(mundlak_tracks)]
        mundlak_rows = mundlak_rows[mundlak_rows["Predictor_Clean"].isin(_MUNDLAK_ONLY)]
        parts.append(mundlak_rows)

    # INT_*: only the interaction term itself
    if int_tracks:
        int_rows = sub[sub["Track"].isin(int_tracks)]
        int_rows = int_rows[int_rows["Predictor_Clean"].str.contains("×", na=False)]
        parts.append(int_rows)

    if not parts:
        return pd.DataFrame(columns=sub.columns)

    result = pd.concat(parts, ignore_index=True)
    return result


def generate_master_plots(df, out_dir):
    """Generate one master forest PNG per model type."""
    os.makedirs(out_dir, exist_ok=True)

    df = df.copy()
    df["Predictor_Clean"] = df["Predictor"].apply(clean_predictor_name)

    # Infer xlabel from the first track
    first_track = df["Track"].iloc[0] if len(df) > 0 else ""
    xlabel = get_track_xlabel(first_track)

    for mtype in MODEL_TYPES_TO_PLOT:
        df_mtype = df[df["Model_Type"] == mtype]
        if df_mtype.empty:
            continue

        print(f"\n  Master plot: {mtype}")

        # Build unified predictor order across all parliaments
        predictor_order, divider_y = _build_master_predictor_order(df_mtype)
        if not predictor_order:
            print(f"    No predictors found, skipping")
            continue

        n_rows_global = len(predictor_order)

        images = {}
        for i, parl in enumerate(PARL_ORDER):
            sub = _collect_master_rows(df_mtype, parl)
            if sub.empty:
                continue

            img = make_subplot(
                parl, sub, predictor_order,
                show_ylabel=(i == 0),
                n_rows_global=n_rows_global,
                xlabel=xlabel,
                divider_y=divider_y,
            )
            if img is not None:
                images[parl] = img

        if not images:
            continue

        out_path = os.path.join(out_dir, f"master_{mtype}.png")
        assemble_final_png(
            title_text=f"Master — {mtype.replace('_', ' ')}",
            panel_images=images,
            xlabel=xlabel,
            out_path=out_path,
            footnote_text=(
                "Main effects from baseline model; speech rate & sentiment "
                "between/within from Mundlak model; interactions each from "
                "separate models. See individual PNGs or CSV for full details."
            ),
        )


