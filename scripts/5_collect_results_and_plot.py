def generate_forest_plots(df, out_dir):
    """Generate 5-panel forest PNGs for each (Track, Model_Type) combo."""
    os.makedirs(out_dir, exist_ok=True)

    df = df.copy()
    df["Predictor_Clean"] = df["Predictor"].apply(clean_predictor_name)

    for track in sorted(df["Track"].unique()):
        for mtype in MODEL_TYPES_TO_PLOT:
            subset = df[(df["Track"] == track) & (df["Model_Type"] == mtype)]
            if subset.empty:
                continue

            plot_label = f"{track}_{mtype}"
            xlabel = get_track_xlabel(track)
            print(f"\n  Plotting: {plot_label}")

            parl_pred_orders = {}
            for parl in PARL_ORDER:
                sub = subset[subset["Parliament"] == parl]
                if sub.empty:
                    continue
                parl_pred_orders[parl] = get_ordered_predictors(
                    sub, is_global=(parl == "global"),
                    drop_intercept=DROP_INTERCEPT, drop_lang=DROP_LANG)

            if not parl_pred_orders:
                print(f"    No parliaments found, skipping")
                continue

            n_rows_global = max(len(v) for v in parl_pred_orders.values())

            images = {}
            for i, parl in enumerate(PARL_ORDER):
                if parl not in parl_pred_orders:
                    continue
                sub = subset[subset["Parliament"] == parl]
                img = make_subplot(
                    parl, sub, parl_pred_orders[parl],
                    show_ylabel=(i == 0),
                    n_rows_global=n_rows_global,
                    xlabel=xlabel,
                )
                if img is not None:
                    images[parl] = img

            if not images:
                continue

            out_path = os.path.join(out_dir, f"{plot_label}.png")
            assemble_final_png(
                title_text=plot_label.replace("_", " "),
                panel_images=images,
                xlabel=xlabel,
                out_path=out_path,
            )


